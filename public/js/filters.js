/**
 * The file filters, as in Graphite's file list: which kind of file to show
 * (code, tests, or all), whether to hide viewed, deleted and generated
 * files, and which extensions to hide. The server gives each file its
 * `kind` ("test", "generated", or null; lib/file-kinds.mjs).
 *
 * The kind and generated choices also decide what counts toward every size
 * the page shows; the rest only hide files from view. A file with an
 * unresolved thread shows anyway, so no comment is hidden, though it still
 * counts only as its kind says.
 */
import { state } from "./state.js";

const STORAGE_KEY = "diffview.filters";
// Tests and generated files start hidden, so a branch reads as its code.
const DEFAULTS = { kind: "code", hideViewed: false, hideDeleted: false, hideGenerated: true, hiddenExtensions: [] };
// What Reset shows: everything.
const NOTHING_HIDDEN = { kind: "all", hideViewed: false, hideDeleted: false, hideGenerated: false, hiddenExtensions: [] };

export const KIND_CHOICES = { all: "All", code: "Code", tests: "Tests" };
export const HIDE_CHOICES = { hideViewed: "Viewed", hideDeleted: "Deleted", hideGenerated: "Autogenerated" };

function load() {
  try {
    return { ...DEFAULTS, ...JSON.parse(localStorage.getItem(STORAGE_KEY) ?? "{}") };
  } catch {
    return { ...DEFAULTS };
  }
}

/** The filters chosen in this browser. */
export const filters = load();

export function setFilters(changes) {
  Object.assign(filters, changes);
  localStorage.setItem(STORAGE_KEY, JSON.stringify(filters));
}

export function resetFilters() {
  setFilters(NOTHING_HIDDEN);
}

/** A file's extension as the menu lists it: ".ts" for a.ts and ".bazel" for BUILD.bazel; a name without one, such as Makefile, stands for itself. */
export function extensionOf(path) {
  const name = path.split("/").pop();
  const dot = name.lastIndexOf(".");
  return dot > 0 ? name.slice(dot) : name;
}

/** Whether a file counts toward the sizes shown, by its kind alone. */
export function counted(file) {
  if (file.kind === "generated") return !filters.hideGenerated && filters.kind !== "tests";
  if (filters.kind === "code") return file.kind !== "test";
  if (filters.kind === "tests") return file.kind === "test";
  return true;
}

/** Why the filters hide a file: words such as "tests", "viewed" or ".json"; empty when it shows. */
export function hiddenBecause(file) {
  const reasons = [];
  if (file.kind === "generated" && filters.hideGenerated) reasons.push("autogenerated");
  else if (filters.kind === "code" && file.kind === "test") reasons.push("tests");
  else if (filters.kind === "tests" && file.kind !== "test") reasons.push("code");
  const mark = state.comments.viewed[file.path];
  if (filters.hideViewed && mark && mark === file.sha) reasons.push("viewed");
  if (filters.hideDeleted && file.status === "deleted") reasons.push("deleted");
  const extension = extensionOf(file.path);
  if (filters.hiddenExtensions.includes(extension)) reasons.push(extension);
  return reasons;
}

/** Whether a file's diff is rendered: nothing hides it, or it carries an unresolved thread. */
export function rendered(file) {
  return hiddenBecause(file).length === 0 || state.comments.threads.some((t) => t.path === file.path && t.status !== "resolved");
}

/** Which files are rendered, as one string, so a change in what threads force into view can be noticed. */
export function renderedPaths() {
  return (state.diff?.files ?? []).filter(rendered).map((f) => f.path).join("\0");
}

/** "2 files hidden: tests, autogenerated", or "" when every file shows. */
export function hiddenSummary(files) {
  const hidden = files.filter((f) => !rendered(f));
  if (!hidden.length) return "";
  const reasons = [...new Set(hidden.flatMap(hiddenBecause))];
  return `${hidden.length} ${hidden.length === 1 ? "file" : "files"} hidden: ${reasons.join(", ")}`;
}

const SIZE_KEYS = ["files", "additions", "deletions", "viewed", "changed"];

/** A branch's size from the server ({files, additions, deletions, viewed, changed, byKind}) counting only the kinds shown. */
export function shownSize(size) {
  if (!size?.byKind) return size;
  const { test, generated } = size.byKind;
  const shown = {};
  for (const key of SIZE_KEYS) {
    if (filters.kind === "tests") shown[key] = test[key];
    else shown[key] = size[key] - (filters.kind === "code" ? test[key] : 0) - (filters.hideGenerated ? generated[key] : 0);
  }
  return { ...size, ...shown };
}
